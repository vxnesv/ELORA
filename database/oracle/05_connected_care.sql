-- Evolucao do modelo para cuidado conectado e contextual.
-- Execute conectado ao schema ELORA_APP depois de 01_schema.sql.

CREATE TABLE elora_care_profile (
    profile_id NUMBER NOT NULL,
    diabetes_enabled CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    hypertension_enabled CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    cycle_enabled CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
    meal_reminder_hours NUMBER(2) DEFAULT 4 NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_care_profile PRIMARY KEY (profile_id),
    CONSTRAINT fk_elora_care_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE,
    CONSTRAINT ck_elora_care_flags CHECK (
        diabetes_enabled IN ('Y', 'N')
        AND hypertension_enabled IN ('Y', 'N')
        AND cycle_enabled IN ('Y', 'N')
    ),
    CONSTRAINT ck_elora_meal_hours CHECK (meal_reminder_hours BETWEEN 2 AND 8)
);

CREATE TABLE elora_health_observation (
    observation_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    profile_id NUMBER NOT NULL,
    metric_code VARCHAR2(30 CHAR) NOT NULL,
    value_number NUMBER(12, 3) NOT NULL,
    unit_code VARCHAR2(20 CHAR) NOT NULL,
    source_code VARCHAR2(20 CHAR) NOT NULL,
    external_id VARCHAR2(200 CHAR),
    source_name VARCHAR2(120 CHAR),
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_observation PRIMARY KEY (observation_id),
    CONSTRAINT fk_elora_observation_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE,
    CONSTRAINT ck_elora_observation_metric CHECK (
        metric_code IN (
            'HEART_RATE', 'RESTING_HEART_RATE', 'BLOOD_GLUCOSE',
            'BLOOD_PRESSURE_SYSTOLIC', 'BLOOD_PRESSURE_DIASTOLIC'
        )
    ),
    CONSTRAINT ck_elora_observation_source CHECK (
        source_code IN ('MANUAL', 'HEALTH_CONNECT', 'HEALTH_KIT')
    ),
    CONSTRAINT ck_elora_observation_value CHECK (value_number > 0)
);

CREATE UNIQUE INDEX uq_elora_observation_external
    ON elora_health_observation (
        CASE WHEN external_id IS NOT NULL THEN profile_id END,
        CASE WHEN external_id IS NOT NULL THEN source_code END,
        CASE WHEN external_id IS NOT NULL THEN external_id END
    );

CREATE INDEX ix_elora_observation_profile_date
    ON elora_health_observation (profile_id, recorded_at);

CREATE TABLE elora_routine_event (
    event_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    profile_id NUMBER NOT NULL,
    event_code VARCHAR2(20 CHAR) NOT NULL,
    value_number NUMBER(10, 2),
    unit_code VARCHAR2(20 CHAR),
    recorded_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_routine_event PRIMARY KEY (event_id),
    CONSTRAINT fk_elora_routine_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE,
    CONSTRAINT ck_elora_routine_code CHECK (
        event_code IN ('MEAL', 'INSULIN')
    ),
    CONSTRAINT ck_elora_routine_value CHECK (
        (event_code = 'MEAL' AND value_number IS NULL)
        OR (event_code = 'INSULIN' AND value_number > 0 AND unit_code = 'IU')
    )
);

CREATE INDEX ix_elora_routine_profile_date
    ON elora_routine_event (profile_id, recorded_at);

CREATE TABLE elora_medication_schedule (
    medication_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    profile_id NUMBER NOT NULL,
    encrypted_name CLOB NOT NULL,
    schedule_minutes NUMBER(4) NOT NULL,
    active CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    last_confirmation TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_medication PRIMARY KEY (medication_id),
    CONSTRAINT fk_elora_medication_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE,
    CONSTRAINT ck_elora_medication_minutes CHECK (
        schedule_minutes BETWEEN 0 AND 1439
    ),
    CONSTRAINT ck_elora_medication_active CHECK (active IN ('Y', 'N'))
);

CREATE INDEX ix_elora_medication_profile
    ON elora_medication_schedule (profile_id, active, schedule_minutes);

CREATE TABLE elora_cycle_event (
    cycle_event_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    profile_id NUMBER NOT NULL,
    event_code VARCHAR2(20 CHAR) NOT NULL,
    encrypted_description CLOB,
    recorded_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_cycle_event PRIMARY KEY (cycle_event_id),
    CONSTRAINT fk_elora_cycle_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE,
    CONSTRAINT ck_elora_cycle_code CHECK (
        event_code IN ('PERIOD_START', 'PERIOD_END', 'SYMPTOM')
    )
);

CREATE INDEX ix_elora_cycle_profile_date
    ON elora_cycle_event (profile_id, recorded_at);

