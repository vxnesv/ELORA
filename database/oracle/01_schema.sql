-- Modelo relacional da primeira versao da ELORA.
-- Execute conectado ao schema ELORA_APP em Oracle Autonomous AI Database.

CREATE TABLE elora_profile (
    profile_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    firebase_uid VARCHAR2(128 CHAR) NOT NULL,
    display_name VARCHAR2(80 CHAR) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_profile PRIMARY KEY (profile_id),
    CONSTRAINT uq_elora_profile_firebase UNIQUE (firebase_uid)
);

CREATE TABLE elora_health_record (
    record_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    profile_id NUMBER NOT NULL,
    indicator_code VARCHAR2(20 CHAR) NOT NULL,
    value_number NUMBER(10, 2) NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    source_code VARCHAR2(20 CHAR) DEFAULT 'MANUAL' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_health_record PRIMARY KEY (record_id),
    CONSTRAINT fk_elora_record_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE,
    CONSTRAINT ck_elora_record_indicator CHECK (
        indicator_code IN ('HYDRATION', 'SLEEP', 'HEART_RATE')
    ),
    CONSTRAINT ck_elora_record_range CHECK (
        (indicator_code = 'HYDRATION' AND value_number > 0 AND value_number <= 10000)
        OR (indicator_code = 'SLEEP' AND value_number > 0 AND value_number <= 24)
        OR (indicator_code = 'HEART_RATE' AND value_number > 0 AND value_number <= 300)
    ),
    CONSTRAINT ck_elora_record_source CHECK (
        source_code IN ('MANUAL', 'WEARABLE', 'IMPORT')
    )
);

CREATE INDEX ix_elora_record_profile_date
    ON elora_health_record (profile_id, recorded_at);

CREATE TABLE elora_care_goal (
    goal_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    profile_id NUMBER NOT NULL,
    title VARCHAR2(120 CHAR) NOT NULL,
    active CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_care_goal PRIMARY KEY (goal_id),
    CONSTRAINT fk_elora_goal_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE,
    CONSTRAINT ck_elora_goal_active CHECK (active IN ('Y', 'N'))
);

CREATE INDEX ix_elora_goal_profile
    ON elora_care_goal (profile_id, active);

CREATE TABLE elora_goal_checkin (
    checkin_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    goal_id NUMBER NOT NULL,
    completed_on DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_goal_checkin PRIMARY KEY (checkin_id),
    CONSTRAINT fk_elora_checkin_goal FOREIGN KEY (goal_id)
        REFERENCES elora_care_goal (goal_id) ON DELETE CASCADE,
    CONSTRAINT uq_elora_checkin_day UNIQUE (goal_id, completed_on),
    CONSTRAINT ck_elora_checkin_day CHECK (completed_on = TRUNC(completed_on))
);

CREATE TABLE elora_protection_plan (
    plan_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    profile_id NUMBER NOT NULL,
    risk_code VARCHAR2(20 CHAR) DEFAULT 'GENERAL' NOT NULL,
    title VARCHAR2(120 CHAR) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_protection_plan PRIMARY KEY (plan_id),
    CONSTRAINT fk_elora_plan_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE,
    CONSTRAINT ck_elora_plan_risk CHECK (
        risk_code IN ('GENERAL', 'HEAT', 'FLOOD', 'LANDSLIDE')
    )
);

CREATE INDEX ix_elora_plan_profile
    ON elora_protection_plan (profile_id);

CREATE TABLE elora_plan_task (
    task_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    plan_id NUMBER NOT NULL,
    title VARCHAR2(120 CHAR) NOT NULL,
    position_number NUMBER(5) DEFAULT 1 NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_plan_task PRIMARY KEY (task_id),
    CONSTRAINT fk_elora_task_plan FOREIGN KEY (plan_id)
        REFERENCES elora_protection_plan (plan_id) ON DELETE CASCADE,
    CONSTRAINT ck_elora_task_position CHECK (position_number > 0)
);

CREATE INDEX ix_elora_task_plan
    ON elora_plan_task (plan_id, position_number);

CREATE TABLE elora_work_context (
    context_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    profile_id NUMBER NOT NULL,
    context_code VARCHAR2(20 CHAR) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_work_context PRIMARY KEY (context_id),
    CONSTRAINT fk_elora_work_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE,
    CONSTRAINT uq_elora_work_profile UNIQUE (profile_id),
    CONSTRAINT ck_elora_work_code CHECK (
        context_code IN ('OFFICE', 'HOME', 'COMMERCE', 'EXTERNAL', 'OTHER')
    )
);

CREATE TABLE elora_consultation_note (
    note_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    profile_id NUMBER NOT NULL,
    note_text CLOB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_elora_consult_note PRIMARY KEY (note_id),
    CONSTRAINT fk_elora_note_profile FOREIGN KEY (profile_id)
        REFERENCES elora_profile (profile_id) ON DELETE CASCADE
);

CREATE INDEX ix_elora_note_profile_date
    ON elora_consultation_note (profile_id, created_at);
